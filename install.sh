#!/usr/bin/env bash
# One-time setup: installs KVM/libvirt, the moza-vm command and the udev
# hotplug rule. Run as your normal user; it asks for sudo when needed.
# Safe to re-run (e.g. after changing MOZA_USB_IDS in /etc/moza-vm.conf).
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)"
PREFIX="/opt/moza-vm"
RULE_FILE="/etc/udev/rules.d/99-moza-vm.rules"

# shellcheck source=lib/common.sh
MOZA_VM_CONF="$SRC/moza-vm.conf" . "$SRC/lib/common.sh"

[[ "$(uname -s)" == "Linux" ]] || die "this only runs on Linux."
command -v apt-get >/dev/null || die "apt-get not found. This script targets Linux Mint / Ubuntu / Debian."
[[ $EUID -ne 0 ]] || die "run as your normal user, not root (it uses sudo itself)."

# 1. CPU virtualization ------------------------------------------------------
if ! grep -qE '\b(svm|vmx)\b' /proc/cpuinfo; then
  die "CPU virtualization is turned off.
  Reboot into your BIOS/UEFI setup (usually F2 or Del at boot) and enable
  'SVM Mode' (AMD) or 'Intel Virtualization Technology', then re-run this."
fi
log "CPU virtualization: enabled"

# 2. Packages ---------------------------------------------------------------
log "installing KVM / libvirt packages..."
sudo apt-get update -qq
sudo apt-get install -y \
  qemu-system-x86 qemu-utils libvirt-daemon-system libvirt-clients \
  virtinst virt-manager virt-viewer usbutils \
  xorriso curl python3

sudo systemctl enable --now libvirtd
[[ -e /dev/kvm ]] || die "/dev/kvm is missing even though the CPU supports virtualization. Try rebooting."

# libvirt's NAT network gives the VM internet (Pit House needs it for firmware).
if ! sudo virsh net-info default 2>/dev/null | grep -q 'Active:.*yes'; then
  sudo virsh net-start default >/dev/null 2>&1 || true
fi
sudo virsh net-autostart default >/dev/null

# 3. User groups ------------------------------------------------------------
need_relogin=0
for g in libvirt kvm; do
  if ! grep -qw "$g" <<<"$(id -nG "$USER")"; then
    sudo usermod -aG "$g" "$USER"
    need_relogin=1
  fi
done

# 4. moza-vm files ------------------------------------------------------------
log "installing moza-vm to $PREFIX..."
sudo install -d "$PREFIX/bin" "$PREFIX/lib"
sudo install -m 755 "$SRC/bin/moza-vm" "$PREFIX/bin/moza-vm"
sudo install -m 644 "$SRC/lib/common.sh" "$PREFIX/lib/common.sh"
sudo install -m 755 "$SRC/lib/moza-hotplug" "$PREFIX/lib/moza-hotplug"
sudo ln -sf "$PREFIX/bin/moza-vm" /usr/local/bin/moza-vm
if [[ ! -e /etc/moza-vm.conf ]]; then
  sudo install -m 644 "$SRC/moza-vm.conf" /etc/moza-vm.conf
else
  log "keeping existing /etc/moza-vm.conf"
fi

# 5. udev hotplug rule (generated from MOZA_USB_IDS) -----------------------
# shellcheck source=moza-vm.conf
. /etc/moza-vm.conf
hook="/usr/bin/systemd-run --no-block --quiet $PREFIX/lib/moza-hotplug"
rules="# Generated by moza-vm install.sh from MOZA_USB_IDS. Do not edit; re-run install.sh.\n"
for entry in $MOZA_USB_IDS; do
  entry="${entry,,}"
  vid="${entry%%:*}"
  add_match="ATTR{idVendor}==\"$vid\""
  rm_match="ENV{ID_VENDOR_ID}==\"$vid\""
  if [[ "$entry" == *:* ]]; then
    pid="${entry#*:}"
    add_match+=", ATTR{idProduct}==\"$pid\""
    rm_match+=", ENV{ID_MODEL_ID}==\"$pid\""
  fi
  rules+="ACTION==\"add\", SUBSYSTEM==\"usb\", ENV{DEVTYPE}==\"usb_device\", $add_match, RUN+=\"$hook add \$env{BUSNUM} \$env{DEVNUM}\"\n"
  rules+="ACTION==\"remove\", SUBSYSTEM==\"usb\", ENV{DEVTYPE}==\"usb_device\", $rm_match, RUN+=\"$hook remove \$env{BUSNUM} \$env{DEVNUM}\"\n"
done
printf '%b' "$rules" | sudo tee "$RULE_FILE" >/dev/null
sudo udevadm control --reload-rules
log "udev rule written to $RULE_FILE"

# 6. Report -------------------------------------------------------------------
log "Moza devices currently connected:"
if command -v lsusb >/dev/null && lsusb | grep -i '346e'; then :; else
  log "  (none found. That's fine if the wheel is unplugged. If it IS plugged in,"
  log "   run 'lsusb', find the Moza line, and add its ID to /etc/moza-vm.conf)"
fi

log "done."
if [[ $need_relogin == 1 ]]; then
  log "IMPORTANT: you were added to the libvirt/kvm groups. Log out and back in"
  log "(or reboot) before running create-vm.sh."
fi
log "next step: ./create-vm.sh /path/to/Win10.iso   (hands-off, 30-60 min)"
